// 01-Algoritmos.cs
// Ejemplo: ¿Qué es un algoritmo? Secuencia de pasos para resolver un problema.
// Ejecutar: dotnet run 01-Algoritmos.cs

Console.WriteLine("=== ALGORITMOS ===");
Console.WriteLine();

// Un algoritmo es una secuencia finita, ordenada y definida de pasos.
// Ejemplo: preparar un café con cafetera de cápsulas.

Console.WriteLine("Algoritmo: Preparar un café");
Console.WriteLine("Características:");
Console.WriteLine("  - Preciso: cada paso está claro");
Console.WriteLine("  - Finito: tiene un número determinado de pasos");
Console.WriteLine("  - Tiene entrada: agua, cápsula, taza");
Console.WriteLine("  - Tiene salida: un café");
Console.WriteLine("  - Definido: no hay ambigüedad");
Console.WriteLine("  - Efectivo: cada paso es realizable");
Console.WriteLine();

Console.WriteLine("Pasos del algoritmo:");
Console.WriteLine("  1. Encender la cafetera");
Console.WriteLine("  2. Esperar a que caliente (señal verde)");
Console.WriteLine("  3. Colocar la taza");
Console.WriteLine("  4. Introducir la cápsula");
Console.WriteLine("  5. Pulsar el botón de café");
Console.WriteLine("  6. Esperar a que termine de exprimir");
Console.WriteLine("  7. Retirar la taza");
Console.WriteLine("  8. Apagar la cafetera");

Console.WriteLine();
Console.WriteLine("Resultado: ☕ ¡Café listo!");
